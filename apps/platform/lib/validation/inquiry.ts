import { z } from 'zod';
import { emailField, requestTokenField } from './common';

/**
 * The public inquiry form. Everything here is attacker-controlled, so the rules are tight
 * and the server never trusts the client for the property, the workspace or the consent flag.
 */
export const inquirySchema = z.object({
  propertySlug: z.string().trim().min(1).max(60),
  name: z.string().trim().max(120).optional().or(z.literal('')),
  email: emailField,
  phone: z
    .string()
    .trim()
    .max(40)
    .regex(/^[0-9+()\-.\s]*$/, 'Enter a phone number or leave it blank')
    .optional()
    .or(z.literal('')),
  message: z.string().trim().min(10, 'A sentence or two, please').max(4000),
  consent: z.literal('on', { message: 'Please accept the privacy notice to send this' }),
  /** Generated by the page; the unique index on the hash is what prevents a double submit. */
  requestToken: requestTokenField,
  /** Hidden field. A real person never fills it in. */
  website: z.literal('').optional(),
  source: z.string().trim().max(120).optional(),
});

export type InquiryInput = z.infer<typeof inquirySchema>;

export function firstIssue(error: z.ZodError): string {
  return error.issues[0]?.message ?? 'Check the form and try again.';
}
